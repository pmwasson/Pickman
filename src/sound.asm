.proc soundStatic
    sta         length

loop:
    ldy         waveform,x
:
    dey
    bne         :-
    sta         SPEAKER     ; 4
    inx                     ; 2
    bne         loop
    dec         length
    bne         loop
    rts

length:         .byte       0

.endproc

.proc soundUnable
    ldy         #$10
loop:
    sta         SPEAKER
    ldx         #$F0
pause:
    dex
    bne         pause
    dey
    bne         loop
    rts
.endproc

